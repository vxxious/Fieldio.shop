create function public.hide_seller_store_brand()
returns trigger language plpgsql set search_path = '' as $$
begin
  if exists (select 1 from public.seller_stores where slug = new.slug) then
    new.is_catalogued := false;
  end if;
  return new;
end;
$$;

create trigger hide_seller_store_brand before insert on public.brands
for each row execute function public.hide_seller_store_brand();

revoke all on function public.hide_seller_store_brand() from public, anon, authenticated;

